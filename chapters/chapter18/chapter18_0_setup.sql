-- Chapter 18: common bootstrap for all SQL exercises.
-- Independent of earlier chapters. Run once in a sandbox; stop on the FIRST error.
-- Prerequisites: USERADMIN, SECURITYADMIN and SYSADMIN available.
-- Validation: official Snowflake docs checked October 2026; SQL run live October 2026,
-- except DROP SCHEMA PAYMENTS_DB.PUBLIC, added October 14 and pending a live run.
-- Placeholders: none. Every name is a reserved lab name listed in the README.
-- Roles: USERADMIN creates roles; SECURITYADMIN builds the hierarchy and assigns
-- roles; SYSADMIN owns central objects and hands PAYMENTS_DB to PAYMENTS_ADMIN.
-- Plain CREATE deliberately refuses to overlay pre-existing lab objects.
-- Do not skip a CREATE error and continue into fixture INSERT statements.

-- BLOCK: role hierarchy
USE ROLE USERADMIN;
CREATE ROLE PAYMENTS_ADMIN;
CREATE ROLE PAYMENTS_BUILDER;
CREATE ROLE PAYMENTS_READER;
CREATE ROLE RISK_READER;
CREATE ROLE COST_READER;
CREATE ROLE COST_ADMIN;
USE ROLE SECURITYADMIN;
GRANT ROLE PAYMENTS_BUILDER TO ROLE PAYMENTS_ADMIN;
GRANT ROLE PAYMENTS_READER TO ROLE PAYMENTS_ADMIN;
GRANT ROLE PAYMENTS_ADMIN TO ROLE SYSADMIN;
GRANT ROLE RISK_READER TO ROLE SYSADMIN;
GRANT ROLE COST_READER TO ROLE COST_ADMIN;
GRANT ROLE COST_ADMIN TO ROLE SYSADMIN;
SHOW GRANTS TO ROLE PAYMENTS_ADMIN;

-- BLOCK: lab user assignment. User defaults are not changed.
SET lab_user = CURRENT_USER();
GRANT ROLE PAYMENTS_ADMIN TO USER IDENTIFIER($lab_user);
GRANT ROLE PAYMENTS_BUILDER TO USER IDENTIFIER($lab_user);
GRANT ROLE PAYMENTS_READER TO USER IDENTIFIER($lab_user);
GRANT ROLE RISK_READER TO USER IDENTIFIER($lab_user);
GRANT ROLE COST_READER TO USER IDENTIFIER($lab_user);
GRANT ROLE COST_ADMIN TO USER IDENTIFIER($lab_user);

-- BLOCK: domain database handed to the team administrator.
-- PAYMENTS_ADMIN creates its own schemas in the chapter's delegated-workspace exercise.
-- The default PUBLIC schema is dropped first, because the ownership handoff does not
-- move it and it would stay with SYSADMIN outside managed access.
USE ROLE SYSADMIN;
USE SECONDARY ROLES NONE;
ALTER SESSION SET TIMEZONE = 'UTC';
CREATE DATABASE PAYMENTS_DB;
DROP SCHEMA PAYMENTS_DB.PUBLIC;
GRANT OWNERSHIP ON DATABASE PAYMENTS_DB
  TO ROLE PAYMENTS_ADMIN COPY CURRENT GRANTS;

-- BLOCK: central databases and warehouses (SYSADMIN keeps ownership)
CREATE DATABASE RISK_DB;
CREATE SCHEMA RISK_DB.WORK WITH MANAGED ACCESS;
CREATE DATABASE ROLE RISK_DB.WORK_READER;
CREATE DATABASE CONTROL_DB;
CREATE SCHEMA CONTROL_DB.COST WITH MANAGED ACCESS;

-- Identical baseline; the warehouse exercise then sets per-workload limits.
CREATE WAREHOUSE PAYMENTS_WH
  WAREHOUSE_TYPE = STANDARD
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300;

CREATE WAREHOUSE RISK_WH
  WAREHOUSE_TYPE = STANDARD
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300;

CREATE WAREHOUSE ADMIN_WH
  WAREHOUSE_TYPE = STANDARD
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300;

GRANT USAGE ON WAREHOUSE PAYMENTS_WH TO ROLE PAYMENTS_BUILDER;
GRANT USAGE ON WAREHOUSE PAYMENTS_WH TO ROLE PAYMENTS_READER;
GRANT USAGE ON WAREHOUSE RISK_WH TO ROLE RISK_READER;
GRANT USAGE ON WAREHOUSE ADMIN_WH TO ROLE COST_READER;

-- BLOCK: Risk fixture
USE WAREHOUSE ADMIN_WH;
CREATE TABLE RISK_DB.WORK.REVIEW_QUEUE (review_id INTEGER, status VARCHAR);
INSERT INTO RISK_DB.WORK.REVIEW_QUEUE VALUES (1, 'OPEN'), (2, 'OPEN');
GRANT USAGE ON DATABASE RISK_DB TO DATABASE ROLE RISK_DB.WORK_READER;
GRANT USAGE ON SCHEMA RISK_DB.WORK TO DATABASE ROLE RISK_DB.WORK_READER;
GRANT SELECT ON TABLE RISK_DB.WORK.REVIEW_QUEUE
  TO DATABASE ROLE RISK_DB.WORK_READER;
GRANT DATABASE ROLE RISK_DB.WORK_READER TO ROLE RISK_READER;

-- BLOCK: cost fixture
-- UTC fixture timestamps are stored without timezone after normalization.
-- The TECHFLOW account and warehouse IDs below are synthetic, not actual object IDs.
CREATE TABLE CONTROL_DB.COST.WAREHOUSE_HOURS (
  account_key VARCHAR NOT NULL,
  warehouse_id INTEGER NOT NULL,
  usage_start TIMESTAMP_NTZ NOT NULL,
  used_compute NUMBER(18,6) NOT NULL,
  attributed_compute NUMBER(18,6)
);
INSERT INTO CONTROL_DB.COST.WAREHOUSE_HOURS VALUES
