GRANT USAGE ON DATABASE CONTROL_DB TO ROLE COST_READER;
GRANT USAGE ON SCHEMA CONTROL_DB.COST TO ROLE COST_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA CONTROL_DB.COST TO ROLE COST_READER;

