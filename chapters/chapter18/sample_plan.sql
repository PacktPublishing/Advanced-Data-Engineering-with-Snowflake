-- Chapter 18: generated sandbox provisioning plan. NOT executed by generator.
-- Prerequisites: approved target account; inspect reserved names before running.
-- Validation: docs checked October 2026; SQL not run live during authoring.
-- Placeholders: none; this template uses fixed registry identifiers.
-- Roles: USERADMIN roles; SECURITYADMIN hierarchy; SYSADMIN warehouse and
-- database handoff; the team ADMIN role builds inside its database;
-- ACCOUNTADMIN monitor creation. Stop on every error, including existing names.
-- The default PUBLIC schema is dropped so every team schema is managed access.
-- The warehouse comment records the cost center; Enterprise accounts can tag it too.
-- User/group assignment, accounting registration and expiry enforcement are separate.
USE ROLE USERADMIN;
CREATE ROLE SS_PAYMENTS_SANDBOX_ADMIN;
CREATE ROLE SS_PAYMENTS_SANDBOX_BUILDER;
CREATE ROLE SS_PAYMENTS_SANDBOX_READER;
USE ROLE SECURITYADMIN;
GRANT ROLE SS_PAYMENTS_SANDBOX_BUILDER TO ROLE SS_PAYMENTS_SANDBOX_ADMIN;
GRANT ROLE SS_PAYMENTS_SANDBOX_READER TO ROLE SS_PAYMENTS_SANDBOX_ADMIN;
GRANT ROLE SS_PAYMENTS_SANDBOX_ADMIN TO ROLE SYSADMIN;
USE ROLE SYSADMIN;
USE SECONDARY ROLES NONE;
CREATE WAREHOUSE SS_PAYMENTS_SANDBOX_WH
  WAREHOUSE_TYPE = STANDARD
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 60
  STATEMENT_TIMEOUT_IN_SECONDS = 300
  COMMENT = 'cost_center=CC_PAYMENTS';
GRANT USAGE ON WAREHOUSE SS_PAYMENTS_SANDBOX_WH TO ROLE SS_PAYMENTS_SANDBOX_BUILDER;
GRANT USAGE ON WAREHOUSE SS_PAYMENTS_SANDBOX_WH TO ROLE SS_PAYMENTS_SANDBOX_READER;
CREATE DATABASE SS_PAYMENTS_SANDBOX;
DROP SCHEMA SS_PAYMENTS_SANDBOX.PUBLIC;
GRANT OWNERSHIP ON DATABASE SS_PAYMENTS_SANDBOX
  TO ROLE SS_PAYMENTS_SANDBOX_ADMIN COPY CURRENT GRANTS;
USE ROLE SS_PAYMENTS_SANDBOX_ADMIN;
CREATE SCHEMA SS_PAYMENTS_SANDBOX.WORK WITH MANAGED ACCESS;
CREATE SCHEMA SS_PAYMENTS_SANDBOX.PUBLISHED WITH MANAGED ACCESS;
GRANT USAGE ON DATABASE SS_PAYMENTS_SANDBOX TO ROLE SS_PAYMENTS_SANDBOX_BUILDER;
GRANT USAGE ON SCHEMA SS_PAYMENTS_SANDBOX.WORK TO ROLE SS_PAYMENTS_SANDBOX_BUILDER;
GRANT CREATE TABLE ON SCHEMA SS_PAYMENTS_SANDBOX.WORK TO ROLE SS_PAYMENTS_SANDBOX_BUILDER;
CREATE DATABASE ROLE SS_PAYMENTS_SANDBOX.WORK_READER;
GRANT USAGE ON DATABASE SS_PAYMENTS_SANDBOX TO DATABASE ROLE SS_PAYMENTS_SANDBOX.WORK_READER;
GRANT USAGE ON SCHEMA SS_PAYMENTS_SANDBOX.WORK TO DATABASE ROLE SS_PAYMENTS_SANDBOX.WORK_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA SS_PAYMENTS_SANDBOX.WORK
  TO DATABASE ROLE SS_PAYMENTS_SANDBOX.WORK_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SS_PAYMENTS_SANDBOX.WORK
  TO DATABASE ROLE SS_PAYMENTS_SANDBOX.WORK_READER;
GRANT DATABASE ROLE SS_PAYMENTS_SANDBOX.WORK_READER TO ROLE SS_PAYMENTS_SANDBOX_READER;
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR SS_PAYMENTS_SANDBOX_RM
  WITH CREDIT_QUOTA = 20
       FREQUENCY = MONTHLY
       START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 70 PERCENT DO NOTIFY
           ON 90 PERCENT DO SUSPEND
           ON 100 PERCENT DO SUSPEND_IMMEDIATE;
ALTER WAREHOUSE SS_PAYMENTS_SANDBOX_WH SET RESOURCE_MONITOR = SS_PAYMENTS_SANDBOX_RM;
SHOW WAREHOUSES LIKE 'SS_PAYMENTS_SANDBOX_WH';
SHOW RESOURCE MONITORS LIKE 'SS_PAYMENTS_SANDBOX_RM';
USE ROLE SYSADMIN;
SHOW SCHEMAS IN DATABASE SS_PAYMENTS_SANDBOX;
SHOW GRANTS TO ROLE SS_PAYMENTS_SANDBOX_BUILDER;
SHOW GRANTS TO ROLE SS_PAYMENTS_SANDBOX_READER;
-- EXPECT: one warehouse with its named monitor, quota 20, monthly frequency;
-- the ADMIN role owns the database and both managed schemas;
-- builder creation access in WORK only.
